  // 핸드 정규화
  normalizeHand(card1, card2) {
    const ranks = ['2', '3', '4', '5', '6', '7', '8', '9', 'T', 'J', 'Q', 'K', 'A'];
    const getValue = (r) => ranks.indexOf(r);
    
    let r1 = card1[0].toUpperCase();
    let s1 = card1[1].toLowerCase();
    let r2 = card2[0].toUpperCase();
    let s2 = card2[1].toLowerCase();
    
    // 페어
    if (r1 === r2) return r1 + r2;
    
    // 높은 랭크를 앞으로
    if (getValue(r1) < getValue(r2)) {
      [r1, r2] = [r2, r1];
      [s1, s2] = [s2, s1];
    }
    
    // 수트/오프수트
    const suited = s1 === s2;
    return r1 + r2 + (suited ? 's' : 'o');
  },

  // GTO 액션 가져오기
  getAction(hand, position, facing3bet = false) {
    if (facing3bet) {
      const threebet = this.THREEBET[position];
      if (threebet && threebet[hand]) {
        return threebet[hand];
      }
      // 3bet 레인지에 없으면 폴드
      return { raise: 0, call: 0, fold: 100 };
    } else {
      const rfi = this.RFI[position];
      if (rfi && rfi[hand]) {
        return rfi[hand];
      }
      return { raise: 0, call: 0, fold: 100 };
    }
  }
